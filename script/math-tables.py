#!/usr/bin/env python3
"""Regenerate crates/trek-app/src/math/tables.rs from a KaTeX npm package (MIT).

    curl -sL https://registry.npmjs.org/katex/-/katex-0.19.0.tgz | tar -xz -C /tmp/katex
    python3 -I script/math-tables.py /tmp/katex/package > crates/trek-app/src/math/tables.rs

It reads two files: src/fontMetricsData.js (each glyph's depth, height, italic correction, skew
and width, in ems, for the KaTeX fonts Trek embeds) and src/symbols.ts (every math-mode symbol:
its command, character, font and TeX class). The fonts themselves sit in
crates/trek-app/assets/fonts/KaTeX_*.ttf, copied from the same package's dist/fonts.
"""

import json
import re
import sys

FACES = [
    ("Main-Regular", "MAIN_REGULAR"),
    ("Main-Bold", "MAIN_BOLD"),
    ("Main-Italic", "MAIN_ITALIC"),
    ("Main-BoldItalic", "MAIN_BOLD_ITALIC"),
    ("Math-Italic", "MATH_ITALIC"),
    ("Math-BoldItalic", "MATH_BOLD_ITALIC"),
    ("AMS-Regular", "AMS_REGULAR"),
    ("Caligraphic-Regular", "CALIGRAPHIC_REGULAR"),
    ("Fraktur-Regular", "FRAKTUR_REGULAR"),
    ("Script-Regular", "SCRIPT_REGULAR"),
    ("SansSerif-Regular", "SANS_SERIF_REGULAR"),
    ("Typewriter-Regular", "TYPEWRITER_REGULAR"),
    ("Size1-Regular", "SIZE1_REGULAR"),
    ("Size2-Regular", "SIZE2_REGULAR"),
    ("Size3-Regular", "SIZE3_REGULAR"),
    ("Size4-Regular", "SIZE4_REGULAR"),
]

CLASSES = {
    "mathord": "Class::Ord, true",
    "textord": "Class::Ord, false",
    "bin": "Class::Bin, false",
    "rel": "Class::Rel, false",
    "open": "Class::Open, false",
    "close": "Class::Close, false",
    "punct": "Class::Punct, false",
    "inner": "Class::Inner, false",
    "op": "Class::Op, false",
}


def num(v):
    s = repr(float(v))
    return s


def main(root):
    js = open(f"{root}/src/fontMetricsData.js", encoding="utf-8").read()
    body = js[js.index("{"):].rstrip().rstrip(";")
    # JavaScript, not JSON: drop the trailing commas.
    metrics = json.loads(re.sub(r",(\s*[}\]])", r"\1", body))

    ts = open(f"{root}/src/symbols.ts", encoding="utf-8").read()
    pattern = re.compile(r'^defineSymbol\(math, (main|ams), (\w+), "((?:[^"\\]|\\.)*)", "((?:[^"\\]|\\.)*)"(, true)?\);', re.M)
    symbols = {}
    for font, group, replace, name, accept in pattern.findall(ts):
        if group not in CLASSES:
            continue
        replace = json.loads(f'"{replace}"')
        name = json.loads(f'"{name}"')
        if len(replace) != 1:
            continue
        entry = (replace, font, group)
        symbols.setdefault(name, entry)
        if accept:
            symbols.setdefault(replace, entry)

    out = []
    out.append("//! Generated by script/math-tables.py from KaTeX 0.19.0 (MIT, Khan Academy and other")
    out.append("//! contributors): glyph metrics of the KaTeX fonts and KaTeX's math symbol table. Don't edit.")
    out.append("")
    out.append("#![allow(clippy::approx_constant, clippy::excessive_precision, clippy::unreadable_literal)]")
    out.append("")
    out.append("use super::layout::{Class, SymbolFont};")
    out.append("")
    out.append("/// Depth, height, italic correction, skew and width of a glyph, in ems, by code point.")
    out.append("pub type Metrics = [f32; 5];")
    out.append("")
    for face, const in FACES:
        table = metrics[face]
        rows = sorted((int(k), v) for k, v in table.items())
        out.append(f"pub static {const}: &[(u32, Metrics)] = &[")
        for cp, v in rows:
            vals = ", ".join(num(x) for x in (v + [0.0] * 5)[:5])
            out.append(f"    ({cp}, [{vals}]),")
        out.append("];")
        out.append("")
    out.append("/// Math-mode symbols: command or character, the glyph drawn, its font, its TeX class, and")
    out.append("/// whether it's a letter set in math italic. Sorted by name for binary search.")
    out.append("pub static SYMBOLS: &[(&str, char, SymbolFont, Class, bool)] = &[")
    for name in sorted(symbols, key=lambda s: s.encode("utf-8")):
        replace, font, group = symbols[name]
        font = "SymbolFont::Main" if font == "main" else "SymbolFont::Ams"
        out.append(f"    ({rust_str(name)}, {rust_char(replace)}, {font}, {CLASSES[group]}),")
    out.append("];")
    print("\n".join(out))


def rust_str(s):
    """A Rust string literal, everything outside ASCII escaped (the source stays ASCII)."""
    out = ""
    for c in s:
        if c in '"\\':
            out += "\\" + c
        elif 0x20 <= ord(c) < 0x7F:
            out += c
        else:
            out += f"\\u{{{ord(c):04x}}}"
    return f'"{out}"'


def rust_char(c):
    if c == "'":
        return "'\\''"
    if c == "\\":
        return "'\\\\'"
    if 0x20 <= ord(c) < 0x7F:
        return f"'{c}'"
    return f"'\\u{{{ord(c):04x}}}'"


if __name__ == "__main__":
    main(sys.argv[1])
